/**
 * Navigation overrides: links of script pages changed in the admin tab "Navigation Flow".
 *
 * The script configuration stays untouched; the overrides live in `native.navigationOverrides`
 * of the instance and are applied on top of the converted script navigation at every start - so
 * they survive a resend of the script. Every override carries a snapshot of the links the script
 * had when it was made: a script that delivers other links by now makes the override `stale`,
 * which the admin reports to the user. A stale override is still applied, the panel keeps running
 * with what the user chose.
 *
 * Pure functions, no adapter access - the caller logs what was skipped.
 */
import type { NavigationItemConfig } from '../classes/navigation';
import {
    isMainPageEntry,
    mainPageName,
    type NavigationLinks,
    type NavigationOverride,
    type NavigationOverrideState,
    type PageConfigEntry,
} from '../types/adminShareConfig';
import { assignmentSourceOf, isOverrideStale } from '../types/navigationEdit';

// The link-level helpers are shared with the admin bundle and live in `types/navigationEdit.ts`;
// re-exported here so the adapter side has one module for everything about overrides.
export { isOverrideStale, mergeNavigationOverride, navigationLinksDiffer } from '../types/navigationEdit';

/** An override that could not be applied, with the reason. */
export interface SkippedNavigationOverride {
    page: string;
    /**
     * - `generated`: the page is generated by the adapter from a page item
     * - `replaced`: an admin page replaces the script page on this panel
     * - `unsupported`: the navigation item of the page carries a node name other than its page id
     * - `missing`: the panel has no such page
     */
    reason: 'generated' | 'replaced' | 'unsupported' | 'missing';
}

export interface ApplyNavigationOverridesResult {
    /** The navigation with the overrides applied - a new array, the input is left untouched */
    navigation: NavigationItemConfig[];
    /** Effect of every applied override, by page */
    states: Map<string, NavigationOverrideState>;
    /** Overrides that were not applied */
    skipped: SkippedNavigationOverride[];
}

/**
 * A link value as stored, or `undefined` for an empty one - `''` and `undefined` mean the same.
 *
 * @param value Stored link target.
 * @returns The target, or `undefined` when empty.
 */
function linkOrUndefined(value: string | undefined): string | undefined {
    return value ? value : undefined;
}

/**
 * The links of a navigation item: `left.single` is `prev`, `left.double` is `parent`,
 * `right.single` is `next`, `right.double` is `home`.
 *
 * @param item Navigation item of the converted script configuration.
 * @returns The links; empty ones are left out.
 */
export function linksOfNavigationItem(item: NavigationItemConfig): NavigationLinks {
    const links: NavigationLinks = {};
    if (!item) {
        return links;
    }
    const prev = linkOrUndefined(item.left?.single);
    const next = linkOrUndefined(item.right?.single);
    const home = linkOrUndefined(item.right?.double);
    const parent = linkOrUndefined(item.left?.double);
    if (prev) {
        links.prev = prev;
    }
    if (next) {
        links.next = next;
    }
    if (home) {
        links.home = home;
    }
    if (parent) {
        links.parent = parent;
    }
    return links;
}

/**
 * A copy of a navigation item with `left`/`right` replaced by the given links. Every other field
 * (name, page, optional) stays. Empty links are left out, a link pointing at the item itself is
 * dropped - a page must not navigate to itself.
 *
 * @param item Navigation item to copy.
 * @param links The links the copy gets.
 * @returns The new item, `null` for a `null` item.
 */
export function navigationItemWithLinks(item: NavigationItemConfig, links: NavigationLinks): NavigationItemConfig {
    if (!item) {
        return item;
    }
    const self = new Set([item.name, item.page]);
    const target = (value: string | undefined): string | undefined => {
        const link = linkOrUndefined(value);
        return link && !self.has(link) ? link : undefined;
    };
    const { left: _left, right: _right, ...rest } = item;
    const result: NonNullable<NavigationItemConfig> = { ...rest };
    const prev = target(links.prev);
    const parent = target(links.parent);
    const next = target(links.next);
    const home = target(links.home);
    if (prev || parent) {
        result.left = {};
        if (prev) {
            result.left.single = prev;
        }
        if (parent) {
            result.left.double = parent;
        }
    }
    if (next || home) {
        result.right = {};
        if (next) {
            result.right.single = next;
        }
        if (home) {
            result.right.double = home;
        }
    }
    return result;
}

/**
 * Whether an override can be applied to a navigation item: the node is named like its page. The
 * flow addresses pages by their page id and link targets by node name - an item where both
 * differ (possible in the `navigation` array of a script) cannot be edited safely.
 *
 * @param item Navigation item.
 * @returns True for an item whose node name equals its page id.
 */
export function isOverridableNavigationItem(item: NavigationItemConfig): item is NonNullable<NavigationItemConfig> {
    return !!item && !!item.page && item.name === item.page;
}

/**
 * The links of every page of a navigation, by page id - what the script says before any override.
 *
 * @param navigation Navigation of the converted script configuration.
 * @returns Links by page; `null` entries and items whose node name differs from the page id are
 * skipped - the admin must not offer them for editing.
 */
export function scriptLinksByPage(navigation: readonly NavigationItemConfig[]): Record<string, NavigationLinks> {
    const result: Record<string, NavigationLinks> = {};
    for (const item of navigation) {
        if (isOverridableNavigationItem(item)) {
            result[item.page] = linksOfNavigationItem(item);
        }
    }
    return result;
}

/**
 * Script pages an admin page replaces on a panel - the rule of `createPagesFromConfig` in
 * `admin.ts`: an entry assigned to the panel replaces a script page of the same name when the
 * instance allows admin pages to override script pages; an entry flagged as start page always
 * replaces `main`. An override for such a page would be applied to a navigation node that is
 * taken out again.
 *
 * @param pageConfig Page configuration of the instance (`native.pageConfig`).
 * @param panelTopic Topic of the panel.
 * @param adminOverridesScriptPages The instance option of the same name.
 * @returns Page ids the admin replaces.
 */
export function adminReplacedPageIds(
    pageConfig: readonly PageConfigEntry[],
    panelTopic: string,
    adminOverridesScriptPages: boolean,
): string[] {
    const result: string[] = [];
    for (const entry of pageConfig) {
        if (!entry || !entry.navigationAssignment || !entry.card) {
            continue;
        }
        const source = assignmentSourceOf(entry, panelTopic);
        if (source !== 'panel' && source !== 'all') {
            continue;
        }
        const pageId = isMainPageEntry(entry) ? mainPageName : entry.uniqueName;
        if ((adminOverridesScriptPages || pageId === mainPageName) && pageId && !result.includes(pageId)) {
            result.push(pageId);
        }
    }
    return result;
}

/**
 * Applies the navigation overrides of one panel to the converted script navigation.
 *
 * Only overrides of `panelTopic` are considered. Skipped are overrides for a generated page (its
 * navigation is read-only), for a page an admin page replaces on this panel (the node is taken
 * out again), for a navigation item whose node name differs from its page id (see
 * {@link isOverridableNavigationItem}) and for a page the navigation does not know (the script
 * no longer delivers it). A stale override (script changed since) is applied nonetheless, so the
 * panel keeps running with what the user chose; the admin reports the difference. An override
 * that leaves a page without any link gets `home = main`, the same default the admin pages get -
 * except for the start page, which is the home.
 *
 * @param navigation Navigation of the converted script configuration - left untouched.
 * @param overrides All overrides of the instance (`native.navigationOverrides`).
 * @param panelTopic Topic of the panel the navigation belongs to.
 * @param generatedPageIds Pages the config manager generated from page items.
 * @param replacedPageIds Pages an admin page replaces on this panel (see {@link adminReplacedPageIds}).
 * @returns The navigation with the overrides applied, their effect and the skipped ones.
 */
export function applyNavigationOverrides(
    navigation: readonly NavigationItemConfig[],
    overrides: readonly NavigationOverride[],
    panelTopic: string,
    generatedPageIds: readonly string[],
    replacedPageIds: readonly string[] = [],
): ApplyNavigationOverridesResult {
    const result: NavigationItemConfig[] = navigation.map(item => (item ? structuredClone(item) : item));
    const states = new Map<string, NavigationOverrideState>();
    const skipped: SkippedNavigationOverride[] = [];
    const generated = new Set(generatedPageIds);
    const replaced = new Set(replacedPageIds);
    for (const override of overrides) {
        if (!override || override.panelTopic !== panelTopic || !override.page) {
            continue;
        }
        if (generated.has(override.page)) {
            skipped.push({ page: override.page, reason: 'generated' });
            continue;
        }
        if (replaced.has(override.page)) {
            skipped.push({ page: override.page, reason: 'replaced' });
            continue;
        }
        const index = result.findIndex(item => item && item.page === override.page);
        const item = index === -1 ? null : result[index];
        if (!item) {
            skipped.push({ page: override.page, reason: 'missing' });
            continue;
        }
        if (!isOverridableNavigationItem(item)) {
            skipped.push({ page: override.page, reason: 'unsupported' });
            continue;
        }
        const currentScriptLinks = linksOfNavigationItem(item);
        const navigationLinks: NavigationLinks = { ...(override.navigation ?? {}) };
        let updated = navigationItemWithLinks(item, navigationLinks);
        if (updated && !updated.left && !updated.right && updated.name !== mainPageName) {
            updated = navigationItemWithLinks(item, { home: mainPageName });
        }
        result[index] = updated;
        states.set(override.page, {
            navigation: navigationLinks,
            scriptLinks: { ...(override.scriptLinks ?? {}) },
            stale: isOverrideStale(override, currentScriptLinks),
        });
    }
    return { navigation: result, states, skipped };
}

/**
 * Records a page the config manager generated from a page item, so its navigation stays
 * read-only in the admin. The list is created on first use; a page is recorded once.
 *
 * @param target Panel configuration being built.
 * @param target.generatedPageIds The list, created when missing.
 * @param pageId `uniqueName` of the generated page.
 */
export function recordGeneratedPage(target: { generatedPageIds?: string[] }, pageId: string): void {
    if (!pageId) {
        return;
    }
    if (!target.generatedPageIds) {
        target.generatedPageIds = [];
    }
    if (!target.generatedPageIds.includes(pageId)) {
        target.generatedPageIds.push(pageId);
    }
}
